import {bootstrapAdmin} from './admin-bootstrap.js';
import {accountRouter} from './account.js';
import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,readFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {randomBytes} from 'node:crypto';
import EmbeddedPostgres from 'embedded-postgres';
import {Pool} from 'pg';
import {getMigrations} from 'better-auth/db/migration';
import request from 'supertest';
import {createAuth} from './auth.js';
import {readConfig} from './config.js';
import {createApp} from './app.js';
import {Router} from 'express';
import {adminRouter} from './admin.js';
import {catalogRouter} from './catalog.js';

test('real PostgreSQL: auth migrations, verified login, sessions and catalog queries', {timeout:120000},async()=>{
 const dir=await mkdtemp(join(tmpdir(),'knokh-integration-'));
 const password=randomBytes(24).toString('hex');
 const db=new EmbeddedPostgres({databaseDir:join(dir,'db'),user:'knokh',password,port:46867,postgresFlags:['-c','unix_socket_directories='],persistent:false,autoRehydrateSymlinks:true,onLog:()=>{},onError:()=>{}});
 let started=false;
 const pool=new Pool({connectionString:`postgresql://knokh:${password}@127.0.0.1:46867/postgres`});
 try{
  await db.initialise();await db.start();started=true;
  const config=readConfig({NODE_ENV:'test',DATABASE_URL:`postgresql://knokh:${password}@127.0.0.1:46867/postgres`,AUTH_SECRET:randomBytes(32).toString('hex'),BETTER_AUTH_URL:'http://localhost:3001',FRONTEND_URL:'http://localhost:5173'});
  const mail:{to:string,text:string}[]=[];
  const auth=createAuth(pool,config,async(to,_subject,text)=>{mail.push({to,text})});
  await (await getMigrations(auth.options)).runMigrations();
  const repeat=await getMigrations(auth.options);assert.equal(repeat.toBeCreated.length,0);
  const sql=await readFile(new URL('../../../database/migrations/20261114140018_outstanding_starhawk/migration.sql',import.meta.url),'utf8');await pool.query(sql);
  await pool.query(await readFile(new URL('../../../database/migrations/20261114190515_talented_jimmy_woo/migration.sql',import.meta.url),'utf8'));
  const app=createApp(config,auth,async()=>{await pool.query('SELECT 1')},Router().use(catalogRouter(pool)).use(adminRouter(pool,auth,config.FRONTEND_URL)).use(accountRouter(pool,auth,config.FRONTEND_URL)));
  const agent=request.agent(app);
  const email='buyer@example.test';
  await agent.post('/api/auth/sign-up/email').set('Origin',config.FRONTEND_URL).send({name:'Test Buyer',email,password:'Strong-test-password-123!'}).expect(200);
  assert.equal(mail.length,1);
  const verify=new URL(mail[0].text);
  await agent.get(verify.pathname+verify.search).expect(302);
  await agent.post('/api/auth/sign-in/email').set('Origin',config.FRONTEND_URL).send({email,password:'Strong-test-password-123!'}).expect(200);
  assert.equal((await pool.query('SELECT "emailVerified" FROM "user" WHERE email=$1',[email])).rows[0].emailVerified,true);
  await request(app).get('/api/account/profile').expect(401);
  const session=await agent.get('/api/auth/get-session').expect(200);assert.equal(session.body.user.email,email);
  const profile=await agent.get('/api/account/profile').expect(200);assert.equal(profile.body.data.email,email);
  await agent.patch('/api/account/profile').set('Origin',config.FRONTEND_URL).send({name:'Updated buyer'}).expect(200);
  await agent.patch('/api/account/profile').set('Origin',config.FRONTEND_URL).send({role:'admin'}).expect(400);
  await agent.patch('/api/account/profile').send({name:'Bad origin'}).expect(403);
  await agent.post('/api/admin/products').set('Origin',config.FRONTEND_URL).send({}).expect(403);
  await bootstrapAdmin(pool,email);
  await assert.rejects(bootstrapAdmin(pool,email),/permanently closed/);
  const input={name:'Admin product',slug:'admin-product',sku:'ADMIN-1',priceMinor:900,currency:'INR',stock:3,status:'published'};
  await agent.post('/api/admin/products').send(input).expect(403);
  const created=await agent.post('/api/admin/products').set('Origin',config.FRONTEND_URL).send(input).expect(201);
  await agent.patch('/api/admin/products/'+created.body.data.id).set('Origin',config.FRONTEND_URL).send({status:'archived'}).expect(200);
  await agent.post('/api/admin/products').set('Origin',config.FRONTEND_URL).send(input).expect(409);
  assert.equal(Number((await pool.query('SELECT COUNT(*) FROM admin_activity_logs')).rows[0].count),3);
  await agent.post('/api/auth/email-otp/send-verification-otp').set('Origin',config.FRONTEND_URL).send({email,type:'sign-in'}).expect(200);
  const otp=mail.at(-1)!.text.match(/\b[0-9]{6}\b/)?.[0];assert.ok(otp);
  const storedOtp=await pool.query('SELECT value FROM verification WHERE identifier LIKE $1',['%'+email+'%']);
  assert.ok(storedOtp.rows.length>0);assert.ok(storedOtp.rows.every(row=>!row.value.includes(otp!)));
  await agent.post('/api/auth/sign-in/email-otp').set('Origin',config.FRONTEND_URL).send({email,otp}).expect(200);
  await agent.post('/api/auth/sign-in/email-otp').set('Origin',config.FRONTEND_URL).send({email,otp}).expect(400);
  const credentials=await pool.query('SELECT password FROM account');assert.ok(credentials.rows[0].password);assert.notEqual(credentials.rows[0].password,'Strong-test-password-123!');
  await agent.post('/api/auth/sign-out').set('Origin',config.FRONTEND_URL).send({}).expect(200);
  const loggedOut=await agent.get('/api/auth/get-session').expect(200);assert.equal(loggedOut.body,null);
  const product=await pool.query("INSERT INTO products(name,slug,status) VALUES ('Test product','test-product','published') RETURNING id");
  const variant=await pool.query("INSERT INTO product_variants(product_id,sku,name,price_minor,currency) VALUES ($1,'TEST-1','Default',12000,'INR') RETURNING id",[product.rows[0].id]);
  await pool.query('INSERT INTO product_inventory(variant_id,on_hand,reserved) VALUES ($1,5,1)',[variant.rows[0].id]);
  const listed=await agent.get('/api/products?inStock=true').expect(200);assert.equal(listed.body.data[0].available_stock,4);assert.equal(listed.body.data[0].price_minor,12000);
  await agent.get('/api/products?minPrice=500&maxPrice=100').expect(400);
  const detail=await agent.get('/api/products/test-product').expect(200);assert.equal(detail.body.data.variants[0].sku,'TEST-1');
  await assert.rejects(pool.query('UPDATE product_inventory SET reserved=6 WHERE variant_id=$1',[variant.rows[0].id]),/inventory_valid/);
  await agent.get('/health/ready').expect(200);
 }finally{await pool.end();if(started)await db.stop();await rm(dir,{recursive:true,force:true})}
});
